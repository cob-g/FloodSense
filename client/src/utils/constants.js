// Point-in-polygon helper using ray-casting algorithm
export const isInNorthCaloocan = (lat, lng) => {
  const polygon = NORTH_CALOOCAN_POLYGON;
  let isInside = false;
  
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const latI = polygon[i][0], lngI = polygon[i][1];
    const latJ = polygon[j][0], lngJ = polygon[j][1];
    
    // Check if the point is on an edge
    if (latI === lat && lngI === lng) return true;
    
    const intersect = ((lngI > lng) !== (lngJ > lng))
        && (lat < (latJ - latI) * (lng - lngI) / (lngJ - lngI) + latI);
    if (intersect) isInside = !isInside;
  }
  
  return isInside;
};

